// Runs before `dev` and `build`. Copies the PDF reader's worker and the OCR engine + English language data
// from node_modules into public/, so the app never loads code or data from another website.
import { copyFileSync, cpSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const mod = (p) => join(root, "node_modules", p);
const copy = (from, to) => {
  if (!existsSync(mod(from))) throw new Error(`Missing ${from}. Run npm install.`);
  mkdirSync(dirname(join(root, "public", to)), { recursive: true });
  copyFileSync(mod(from), join(root, "public", to));
};

copy("tesseract.js/dist/worker.min.js", "ocr/worker.min.js");
for (const core of ["tesseract-core-lstm.wasm.js", "tesseract-core-simd-lstm.wasm.js", "tesseract-core-relaxedsimd-lstm.wasm.js"]) copy(`tesseract.js-core/${core}`, `ocr/${core}`);
copy("@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz", "ocr/lang/eng.traineddata.gz");

copy("pdfjs-dist/legacy/build/pdf.worker.min.mjs", "pdfjs/pdf.worker.min.mjs");
cpSync(mod("pdfjs-dist/standard_fonts"), join(root, "public", "pdfjs", "standard_fonts"), { recursive: true });
// Safari (before 18.4) can't iterate a ReadableStream with `for await`, which the PDF worker does
writeFileSync(join(root, "public", "pdfjs", "worker.mjs"), `// Generated by scripts/prepare-public.mjs
if (typeof ReadableStream !== "undefined" && !ReadableStream.prototype[Symbol.asyncIterator]) {
  ReadableStream.prototype.values = function ({ preventCancel = false } = {}) {
    const reader = this.getReader();
    return {
      async next() { const r = await reader.read(); if (r.done) reader.releaseLock(); return r; },
      async return(value) { if (!preventCancel) { const p = reader.cancel(value); reader.releaseLock(); await p; } else reader.releaseLock(); return { done: true, value }; },
      [Symbol.asyncIterator]() { return this; },
    };
  };
  ReadableStream.prototype[Symbol.asyncIterator] = ReadableStream.prototype.values;
}
if (typeof Promise.withResolvers !== "function") {
  Promise.withResolvers = function () { let resolve, reject; const promise = new Promise((a, b) => { resolve = a; reject = b; }); return { promise, resolve, reject }; };
}
await import("./pdf.worker.min.mjs");
`);
console.log("prepare-public: PDF worker and OCR files copied to public/");
